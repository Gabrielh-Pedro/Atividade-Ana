// Safe handling of URL parameters
window.onload = function() {
    const urlParams = new URLSearchParams(window.location.search);
    if (urlParams.has('welcome')) {
        const welcomeMessage = urlParams.get('welcome');
        // Sanitize and use textContent instead of innerHTML
        document.getElementById('results').textContent = sanitizeHTML(welcomeMessage);
    }
    
    // Add CSRF token to all forms
    addCSRFTokenToForms();
};

// Add CSRF protection to forms
function addCSRFTokenToForms() {
    // In a real app, this token would be generated by the server
    const csrfToken = 'secure-token-' + Date.now();
    
    // Add to all forms
    document.querySelectorAll('form').forEach(form => {
        const tokenInput = document.createElement('input');
        tokenInput.type = 'hidden';
        tokenInput.name = 'csrf_token';
        tokenInput.value = csrfToken;
        form.appendChild(tokenInput);
    });
} 