// XSS prevention with proper sanitization
document.getElementById('searchForm').addEventListener('submit', function(e) {
    e.preventDefault();
    const query = document.getElementById('searchQuery').value;
    
    // Sanitize input before displaying
    const sanitizedQuery = sanitizeHTML(query);
    document.getElementById('results').textContent = 'Results for: ' + sanitizedQuery;
    
    // Simulate an AJAX call
    setTimeout(() => {
        // Create elements properly instead of using innerHTML
        const resultDiv = document.createElement('div');
        const resultText = document.createTextNode('Result found: ');
        const resultSpan = document.createElement('span');
        resultSpan.textContent = sanitizedQuery;
        
        resultDiv.appendChild(resultText);
        resultDiv.appendChild(resultSpan);
        document.getElementById('results').appendChild(resultDiv);
    }, 500);
});

// HTML sanitization function
function sanitizeHTML(str) {
    const temp = document.createElement('div');
    temp.textContent = str;
    return temp.innerHTML;
}

